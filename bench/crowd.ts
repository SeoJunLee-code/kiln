// Many entities: time per tick and bytes per tick. Two scenes: things that only move
// (`drift`) and bodies that fall onto a floor and slide, each with a collision query
// every tick (`fall`).
//   node --min-semi-space-size=128 --max-semi-space-size=128 bench/crowd.ts [COUNT] [--write]
// --write updates CROWD.md. Numbers are from whatever machine runs this, one thread,
// no rendering. tests/alloc.test.ts holds the allocation over a smaller crowd.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseScene } from '../src/scene.ts';
import { hash, step } from '../src/sim.ts';
import type { World } from '../src/world.ts';
import { median } from './alloc.ts';

export type Kind = 'drift' | 'fall';

export function crowd(count: number, kind: Kind): World {
  let seed = 12345;
  const rnd = (n: number): number => (seed = (Math.imul(seed, 1103515245) + 12345) >>> 0) % n;
  const width = Math.ceil(Math.sqrt(count) * 12);
  const out = [kind === 'drift' ? 'world hz=60' : 'world hz=60 gravity=0,30'];
  if (kind === 'fall') out.push(`entity floor\n  pos 0 60\n  box ${width} 2\n  solid`);
  for (let i = 0; i < count; i++) {
    out.push(kind === 'drift'
      ? `entity m${i}\n  pos ${rnd(width)} ${rnd(width)}\n  vel ${rnd(9) - 4} ${rnd(9) - 4}`
      : `entity m${i}\n  pos ${rnd(width - 1)}.${rnd(9)} ${rnd(55)}\n  box 0.8 0.8\n  vel ${rnd(9) - 4} 0\n  body`);
  }
  return parseScene(out.join('\n') + '\n').world;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const count = Number(process.argv[2]) || 100000;
  const rows: string[] = [];
  for (const kind of ['drift', 'fall'] as const) {
    const w = crowd(count, kind);
    for (let i = 0; i < 120; i++) step(w);
    const ticks = 300;
    const t0 = performance.now();
    for (let i = 0; i < ticks; i++) step(w);
    const ms = (performance.now() - t0) / ticks;
    const bytes = median(() => { for (let i = 0; i < 20; i++) step(w); }, 20, 11);
    rows.push(`| ${kind} | ${count} | ${ms.toFixed(1)} | ${ms <= 1000 / 60 ? 'yes' : 'no'} | ${bytes} | ${hash(w)} |`);
    console.error(rows[rows.length - 1]);
  }
  const out = `# Many entities

Generated by \`node --min-semi-space-size=128 --max-semi-space-size=128 bench/crowd.ts --write\`.
Node ${process.version.split('.')[0]}, one laptop-class machine, one thread, no rendering.
\`drift\`: entities with a position and a velocity. \`fall\`: bodies under gravity with a box
each, on one floor, so every one runs a collision query every tick.

| Scene | Entities | ms per tick | fits 60 Hz | bytes allocated per tick | final hash |
|---|---|---|---|---|---|
${rows.join('\n')}

The time is one run on a machine that is not quiet; expect some noise. The hash is there
so that an optimisation which changes results cannot go unnoticed.
`;
  process.stdout.write(out);
  if (process.argv.includes('--write')) writeFileSync(new URL('CROWD.md', import.meta.url), out);
}
