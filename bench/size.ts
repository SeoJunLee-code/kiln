import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const sets: Record<string, string[]> = {
  Kiln: ['examples/maze.kiln', 'examples/maze.input'],
  'Godot 4': ['bench/godot/maze.tscn', 'bench/godot/player.gd', 'bench/godot/coin.gd', 'bench/godot/exit.gd', 'bench/godot/test_maze.gd'],
};

const rows: string[] = [];
const totals: Record<string, number> = {};
for (const [name, files] of Object.entries(sets)) {
  let chars = 0, bytes = 0, lines = 0;
  for (const f of files) {
    // Normalise line endings so the numbers do not depend on git's autocrlf setting.
    const text = readFileSync(new URL(f, root), 'utf8').replace(/\r\n/g, '\n');
    const c = text.length, b = Buffer.byteLength(text), l = text.split('\n').filter((x) => x.trim()).length;
    rows.push(`| ${name} | \`${f}\` | ${l} | ${c} | ${b} | ${Math.round(c / 4)} |`);
    chars += c; bytes += b; lines += l;
  }
  rows.push(`| **${name}** | **total (${files.length} files)** | **${lines}** | **${chars}** | **${bytes}** | **${Math.round(chars / 4)}** |`);
  totals[name] = chars;
}

const ratio = (totals['Godot 4'] / totals.Kiln).toFixed(1);
const out = `# Results

Generated by \`node bench/size.ts\`. See [README.md](README.md) for what this does and does not show.

| Engine | File | Non-blank lines | Characters | Bytes | Tokens (est. chars/4) |
|---|---|---|---|---|---|
${rows.join('\n')}

For this one game the Godot version is ${ratio}x the characters of the Kiln version.
The Godot files were not run in Godot.
`;
writeFileSync(new URL('bench/RESULTS.md', root), out);
process.stdout.write(out);
