// Simulation speed: milliseconds per tick for a world of falling, sliding bodies among
// solid blocks. Run with `node bench/perf.ts`; add --write to update PERF.md.
// Numbers are from whatever machine runs this, single thread, no rendering.
import { writeFileSync } from 'node:fs';
import { cpus } from 'node:os';
import { parseScene } from '../src/scene.ts';
import { hash, step } from '../src/sim.ts';

/** A wide floor with `solids` scattered blocks and `movers` bodies dropped above it. */
function scene(movers: number, solids: number): string {
  let seed = 12345;
  const rnd = (n: number): number => (seed = (Math.imul(seed, 1103515245) + 12345) >>> 0) % n;
  const width = Math.max(200, Math.ceil(Math.sqrt(movers + solids) * 12));
  const out = ['world hz=60 gravity=0,30', `entity floor\n  pos 0 60\n  box ${width} 2\n  solid`,
    `entity left\n  pos -2 0\n  box 2 62\n  solid`, `entity right\n  pos ${width} 0\n  box 2 62\n  solid`];
  for (let i = 0; i < solids - 3; i++) out.push(`entity s${i}\n  pos ${rnd(width - 2)} ${20 + rnd(38)}\n  box ${1 + rnd(3)} 1\n  solid`);
  for (let i = 0; i < movers; i++) out.push(`entity m${i}\n  pos ${rnd(width - 1)}.${rnd(9)} ${rnd(15)}\n  box 0.8 0.8\n  vel ${rnd(9) - 4} 0\n  body`);
  return out.join('\n') + '\n';
}

const rows: string[] = [];
for (const [movers, solids] of [[100, 100], [1000, 100], [1000, 1000], [5000, 1000], [10000, 5000]].slice(0, +(process.env.KILN_PERF_ROWS ?? 5))) {
  const w = parseScene(scene(movers, solids)).world;
  for (let i = 0; i < 30; i++) step(w); // warm up
  const ticks = movers >= 5000 ? 120 : 300;
  const t0 = performance.now();
  for (let i = 0; i < ticks; i++) step(w);
  const ms = (performance.now() - t0) / ticks;
  console.error(`${movers} movers, ${solids} solids: ${ms.toFixed(3)} ms/tick`);
  rows.push(`| ${movers} | ${solids} | ${ms.toFixed(3)} | ${Math.round(1000 / ms)} | ${ms <= 1000 / 60 ? 'yes' : 'no'} | ${hash(w)} |`);
}

const out = `# Simulation speed

Generated by \`node bench/perf.ts --write\`. Bodies fall under gravity and slide among solid
blocks, so every body runs a collision query every tick. One thread, no rendering.

Machine: ${cpus()[0].model.trim()}, Node ${process.version}. One run; expect some noise.

| Moving bodies | Solid blocks | ms per tick | ticks per second | fits 60 Hz | final hash |
|---|---|---|---|---|---|
${rows.join('\n')}

The hash column is there so that an optimisation which changes results cannot go unnoticed.
`;
process.stdout.write(out);
if (process.argv.includes('--write')) writeFileSync(new URL('PERF.md', import.meta.url), out);
